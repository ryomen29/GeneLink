-- Score monitoring view for the admin dashboard.
create or replace view public.student_score_summary
with (security_invoker = true)
as
select
  p.id as student_id,
  p.full_name,
  p.email,
  coalesce(round(avg(pa.score::numeric / nullif(pa.total_questions, 0) * 100)), 0)::int as pretest,
  coalesce((
    select round(avg(fa.score::numeric / nullif(fa.total_questions, 0) * 100))
    from public.final_exam_attempts fa
    where fa.student_id = p.id
  ), 0)::int as final,
  coalesce(round((
    avg(pa.score::numeric / nullif(pa.total_questions, 0) * 100) +
    coalesce((
      select avg(fa.score::numeric / nullif(fa.total_questions, 0) * 100)
      from public.final_exam_attempts fa
      where fa.student_id = p.id
    ), 0)
  ) / 2), 0)::int as average,
  case
    when coalesce((
      select avg(fa.score::numeric / nullif(fa.total_questions, 0) * 100)
      from public.final_exam_attempts fa
      where fa.student_id = p.id
    ), 0) >= 75 then 'Excellent'
    when coalesce((
      select avg(fa.score::numeric / nullif(fa.total_questions, 0) * 100)
      from public.final_exam_attempts fa
      where fa.student_id = p.id
    ), 0) >= 60 then 'On track'
    else 'Needs support'
  end as status
from public.profiles p
left join public.pretest_attempts pa on pa.student_id = p.id
where p.role = 'student'
group by p.id, p.full_name, p.email;

