create extension if not exists pgcrypto;

create type public.app_role as enum ('student', 'admin');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  role public.app_role not null default 'student',
  created_at timestamptz not null default now()
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  title text not null,
  emoji text not null default '🧬',
  color text not null default 'mint',
  objectives jsonb not null default '[]'::jsonb,
  sort_order int not null unique
);

create table public.topics (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  title text not null,
  content text not null default '',
  sort_order int not null,
  unique (lesson_id, sort_order)
);

create table public.pretest_questions (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  question text not null,
  options jsonb not null,
  correct_answer smallint not null,
  sort_order int not null,
  unique (lesson_id, sort_order)
);

create table public.pretest_attempts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  answers jsonb not null,
  score int not null check (score >= 0),
  total_questions int not null default 5,
  started_at timestamptz not null default now(),
  submitted_at timestamptz not null default now()
);

create table public.student_lesson_progress (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  pretest_completed boolean not null default false,
  completed_at timestamptz,
  unique (student_id, lesson_id)
);

create table public.student_topic_progress (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  topic_id bigint not null references public.topics(id) on delete cascade,
  completed_at timestamptz not null default now(),
  unique (student_id, topic_id)
);

create table public.final_exam_questions (
  id bigint generated by default as identity primary key,
  question text not null,
  options jsonb not null,
  correct_answer smallint not null,
  lesson_id bigint references public.lessons(id) on delete set null,
  sort_order int not null unique
);

create table public.final_exam_attempts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  answers jsonb not null,
  score int not null,
  total_questions int not null,
  submitted_at timestamptz not null default now()
);

create table public.ai_conversations (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  title text,
  created_at timestamptz not null default now()
);

create table public.ai_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.ai_conversations(id) on delete cascade,
  role text not null check (role in ('student', 'ai')),
  message text not null,
  created_at timestamptz not null default now()
);

-- Automatically create a student profile when a new Auth user is registered.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'Explorer'),
    new.email,
    'student'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

