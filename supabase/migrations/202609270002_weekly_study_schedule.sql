-- GENELInK's recurring weekly schedule. Additive: existing curriculum and
-- assessment tables remain the source for lessons, topics, and scores.
create table if not exists public.study_schedule (
  id bigint generated by default as identity primary key,
  name text not null,
  timezone text not null default 'Asia/Manila',
  cycle_type text not null default 'weekly' check (cycle_type = 'weekly'),
  cycle_days smallint not null default 7 check (cycle_days = 7),
  session_start time not null default time '08:00',
  session_end time not null default time '08:45',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (session_start < session_end)
);

create unique index if not exists study_schedule_one_active_idx
  on public.study_schedule (is_active)
  where is_active;

create table if not exists public.weekly_learning_schedule (
  id bigint generated by default as identity primary key,
  day_number smallint not null unique check (day_number between 1 and 7),
  activity_type text not null check (activity_type in ('pretest', 'lesson', 'post_test')),
  lesson_id bigint references public.lessons(id) on delete set null,
  title text not null,
  description text,
  sort_order smallint not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (activity_type = 'lesson' and lesson_id is not null)
    or (activity_type in ('pretest', 'post_test'))
  )
);

